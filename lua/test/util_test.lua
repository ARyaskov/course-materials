local util = require("sift.util")

describe("util.Buffer", function()
  it("собирает строку одним concat", function()
    local b = util.Buffer.new(4)
    b:put("a"):putf("%d-%s", 7, "x"):put("z")
    assert.equal(b:concat(), "a7-xz")
    assert.equal(#b, 3)
    assert.equal(tostring(b), "a7-xz")
  end)

  it("поддерживает разделитель", function()
    assert.equal(util.Buffer.new():put("a"):put("b"):concat("|"), "a|b")
  end)
end)

describe("util.parse_rfc3339", function()
  it("не зависит от часового пояса", function()
    assert.equal(util.parse_rfc3339("1970-01-01T00:00:00Z"), 0)
    assert.equal(util.parse_rfc3339("2026-09-01T10:00:00Z"), 1788256800)
  end)

  it("делает полный круг", function()
    local s = "2024-02-29T23:59:59Z"
    assert.equal(util.format_rfc3339(util.parse_rfc3339(s)), s)
  end)

  it("понимает доли секунды", function()
    assert.near(util.parse_rfc3339("2026-09-01T10:00:00.250Z"), 1788256800.25, 1e-6)
  end)

  it("возвращает причину вместо исключения", function()
    local t, why = util.parse_rfc3339("вчера")
    assert.nil_(t)
    assert.truthy(why:find("malformed", 1, true))
    assert.nil_((util.parse_rfc3339("2026-13-01T00:00:00Z")))
  end)
end)

describe("util.pad", function()
  it("считает ширину в символах, а не в байтах", function()
    assert.equal(util.width("цель"), 4)
    assert.equal(#("цель"), 8)
    assert.equal(util.pad("цель", 6), "цель  ")
    assert.equal(util.pad("цель", 6, "right"), "  цель")
    assert.equal(util.pad("длиннее", 3), "длиннее")
  end)

  it("обрезает по границе символа", function()
    local s = util.ellipsis("POST /api/payments/refund", 12)
    assert.equal(utf8.len(s), 12)
    assert.truthy(s:find("...", 1, true))
  end)
end)

describe("util.split", function()
  it("режет по литеральному разделителю", function()
    assert.same(util.split("a,b,,c", ","), { "a", "b", "", "c" })
    assert.same(util.split("solo", ","), { "solo" })
  end)
end)
