package io.meterway.rating;

/** Как ступени превращаются в сумму. */
public enum PricingModel {

    /** Единая цена за единицу для всего объёма. */
    FLAT,

    /**
     * Ступенчатая: каждая ступень тарифицируется по своей цене.
     * 1000 запросов при ступенях 0–500 по 2 и 500+ по 1 дают 500*2 + 500*1.
     */
    GRADUATED,

    /**
     * Объёмная: весь объём тарифицируется по цене той ступени, в которую он попал.
     * Те же 1000 запросов дают 1000*1.
     */
    VOLUME,

    /** Плата за пакет: округление вверх до кратного размеру пакета. */
    PACKAGE
}
