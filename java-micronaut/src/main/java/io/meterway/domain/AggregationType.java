package io.meterway.domain;

/**
 * Способ свернуть события метрики в одно число за окно.
 * Тип агрегации определяет и SQL, и поведение при опоздавших событиях.
 */
public enum AggregationType {

    /** Сумма количеств: запросы к API, переданные гигабайты. Опоздавшее событие просто прибавляется. */
    SUM,

    /** Максимум за окно: пиковое число подключений. Опоздавшее событие может увеличить агрегат. */
    MAX,

    /** Последнее известное значение: размер хранилища на конец периода. */
    LAST,

    /** Число различных значений свойства: уникальные активные пользователи. */
    UNIQUE_COUNT
}
