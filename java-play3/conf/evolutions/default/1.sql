-- Beacon: организации, администраторы, сервисы и HTTP-проверки.
-- DDL написан переносимо: одинаково применяется на PostgreSQL 16 и на H2 2.x,
-- поэтому те же эволюции работают в тестах.

--- !Ups

CREATE TABLE organizations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        VARCHAR(64)  NOT NULL,
    name        VARCHAR(200) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_organizations_slug UNIQUE (slug)
);

CREATE TABLE admin_users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id         BIGINT       NOT NULL,
    email          VARCHAR(200) NOT NULL,
    password_hash  VARCHAR(200) NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_admin_users_email UNIQUE (email),
    CONSTRAINT fk_admin_users_org FOREIGN KEY (org_id) REFERENCES organizations (id)
);

CREATE TABLE services (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id       BIGINT       NOT NULL,
    service_key  VARCHAR(64)  NOT NULL,
    name         VARCHAR(200) NOT NULL,
    description  VARCHAR(1000),
    position     INTEGER      NOT NULL DEFAULT 0,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_services_org_key UNIQUE (org_id, service_key),
    CONSTRAINT fk_services_org FOREIGN KEY (org_id) REFERENCES organizations (id)
);

CREATE TABLE checks (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id       BIGINT       NOT NULL,
    name             VARCHAR(200) NOT NULL,
    method           VARCHAR(10)  NOT NULL DEFAULT 'GET',
    url              VARCHAR(2000) NOT NULL,
    expected_status  INTEGER      NOT NULL DEFAULT 200,
    body_contains    VARCHAR(500),
    timeout_ms       INTEGER      NOT NULL DEFAULT 10000,
    interval_seconds INTEGER      NOT NULL DEFAULT 60,
    enabled          BOOLEAN      NOT NULL DEFAULT TRUE,
    next_run_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_checks_service FOREIGN KEY (service_id) REFERENCES services (id)
);

CREATE INDEX ix_checks_due ON checks (enabled, next_run_at);
CREATE INDEX ix_checks_service ON checks (service_id);

--- !Downs

DROP TABLE checks;
DROP TABLE services;
DROP TABLE admin_users;
DROP TABLE organizations;
