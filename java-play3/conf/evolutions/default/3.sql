-- Инциденты, обновления инцидентов, вебхуки и ключи API.

--- !Ups

CREATE TABLE incidents (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id    BIGINT       NOT NULL,
    title         VARCHAR(300) NOT NULL,
    severity      VARCHAR(16)  NOT NULL DEFAULT 'MAJOR',
    opened_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at   TIMESTAMP WITH TIME ZONE,
    auto_created  BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_incidents_service FOREIGN KEY (service_id) REFERENCES services (id)
);

CREATE INDEX ix_incidents_service_open ON incidents (service_id, resolved_at);

CREATE TABLE incident_updates (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id  BIGINT       NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status       VARCHAR(32)  NOT NULL,
    body         VARCHAR(2000) NOT NULL,
    CONSTRAINT fk_incident_updates_incident FOREIGN KEY (incident_id) REFERENCES incidents (id)
);

CREATE TABLE webhooks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id      BIGINT        NOT NULL,
    url         VARCHAR(2000) NOT NULL,
    secret      VARCHAR(200)  NOT NULL,
    enabled     BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_webhooks_org FOREIGN KEY (org_id) REFERENCES organizations (id)
);

CREATE TABLE api_keys (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id        BIGINT       NOT NULL,
    name          VARCHAR(200) NOT NULL,
    key_prefix    VARCHAR(16)  NOT NULL,
    secret_hash   VARCHAR(128) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used_at  TIMESTAMP WITH TIME ZONE,
    revoked_at    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_api_keys_prefix UNIQUE (key_prefix),
    CONSTRAINT fk_api_keys_org FOREIGN KEY (org_id) REFERENCES organizations (id)
);

--- !Downs

DROP TABLE api_keys;
DROP TABLE webhooks;
DROP TABLE incident_updates;
DROP TABLE incidents;
