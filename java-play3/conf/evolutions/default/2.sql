-- Результаты проб и дневные агрегаты аптайма.

--- !Ups

CREATE TABLE probe_results (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    check_id     BIGINT      NOT NULL,
    started_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    duration_ms  BIGINT      NOT NULL,
    status_code  INTEGER,
    outcome      VARCHAR(16) NOT NULL,
    error        VARCHAR(500),
    CONSTRAINT fk_probe_results_check FOREIGN KEY (check_id) REFERENCES checks (id)
);

CREATE INDEX ix_probe_results_check_time ON probe_results (check_id, started_at);

CREATE TABLE uptime_days (
    check_id     BIGINT NOT NULL,
    day_utc      DATE   NOT NULL,
    up_count     INTEGER NOT NULL DEFAULT 0,
    total_count  INTEGER NOT NULL DEFAULT 0,
    avg_duration_ms BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT pk_uptime_days PRIMARY KEY (check_id, day_utc),
    CONSTRAINT fk_uptime_days_check FOREIGN KEY (check_id) REFERENCES checks (id)
);

--- !Downs

DROP TABLE uptime_days;
DROP TABLE probe_results;
