"""Настройки Gunicorn.

Числа здесь не универсальны: они выведены из профиля нагрузки Depot —
запросы упираются в базу и во внешний платёжный шлюз, то есть ждут
ввода-вывода, а не считают. Отсюда потоки, а не только процессы.
"""

import multiprocessing
import os

#: слушать все интерфейсы внутри контейнера: наружу порт публикует
#: оркестратор, а не приложение
bind = os.environ.get("DEPOT_BIND", "0.0.0.0:8000")

#: формула из документации как отправная точка; окончательное число
#: подбирается по нагрузочному тесту и объёму памяти на процесс
workers = int(os.environ.get("DEPOT_WORKERS", multiprocessing.cpu_count() * 2 + 1))

#: потоки внутри процесса: запрос большую часть времени ждёт ответа базы,
#: и на это время поток освобождает процессор
threads = int(os.environ.get("DEPOT_THREADS", 4))
worker_class = "gthread"

#: перезапуск процесса после N запросов лечит медленные утечки памяти;
#: разброс не даёт всем процессам перезапуститься одновременно
max_requests = 2000
max_requests_jitter = 200

#: запас на завершение текущих запросов при выкладке; должен быть меньше
#: периода ожидания у оркестратора, иначе процесс убьют на середине
graceful_timeout = 30

#: жёсткий предел на запрос: зависший обработчик не должен занимать поток
#: бесконечно
timeout = 60

#: держать соединение дольше, чем это делает обратный прокси, бессмысленно
keepalive = 5

#: защита от переполнения заголовков
limit_request_line = 8190
limit_request_fields = 100
limit_request_field_size = 8190

#: журнал в поток вывода: сбором занимается инфраструктура, а не приложение
accesslog = "-"
errorlog = "-"
loglevel = os.environ.get("DEPOT_LOG_LEVEL", "info").lower()

#: доверенный источник заголовков с исходным адресом клиента
forwarded_allow_ips = os.environ.get("DEPOT_FORWARDED_ALLOW_IPS", "127.0.0.1")

#: приложение импортируется до форка: код и подключения к базе, открытые
#: лениво, не дублируются по процессам, а память страниц разделяется
preload_app = True


def post_fork(server, worker):  # type: ignore[no-untyped-def]
    """Развести соединения после форка.

    Пул, унаследованный от мастера, был бы общим для всех процессов, и они
    начали бы писать в один сокет.
    """
    from depot.extensions import db

    db.engine.dispose()


def worker_int(worker):  # type: ignore[no-untyped-def]
    worker.log.info("worker received INT or QUIT")
