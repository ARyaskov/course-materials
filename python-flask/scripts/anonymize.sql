-- Обезличивание копии рабочей базы для тестового контура.
--
-- Копия боевых данных на машине разработчика — это те же персональные
-- данные, только без охраны. Скрипт выполняется сразу после
-- восстановления дампа и до того, как к базе получит доступ кто-либо,
-- кроме выполняющего восстановление.
--
-- Запуск: psql "$TEST_DATABASE_URL" -f scripts/anonymize.sql

BEGIN;

-- Проверка, что скрипт не запущен по ошибке на рабочей базе.
-- Ошибка здесь дешевле, чем испорченные боевые данные.
DO $$
BEGIN
    IF current_database() NOT LIKE '%test%' AND current_database() NOT LIKE '%staging%' THEN
        RAISE EXCEPTION
            'база % не похожа на тестовую; обезличивание остановлено',
            current_database();
    END IF;
END $$;

-- Адреса заменяются детерминированно: один и тот же пользователь
-- получает один и тот же адрес при каждом обновлении копии, и связи
-- между таблицами остаются осмысленными.
UPDATE users
SET email = 'user' || id || '@example.invalid',
    full_name = 'Пользователь ' || id,
    -- один и тот же хеш для всех: пароль в тестовом контуре известен
    -- и одинаков, восстановить исходный по нему невозможно
    password_hash = 'scrypt:32768:8:1$anonymized$0000000000000000';

-- Домен .invalid зарезервирован стандартом и никогда не будет
-- зарегистрирован: письмо, случайно отправленное из тестового контура,
-- физически не дойдёт до живого адресата.

UPDATE refresh_sessions
SET ip = NULL,
    user_agent = NULL;

-- Сессии не просто обезличиваются, а отзываются: живой токен обновления
-- из копии открывал бы доступ к тестовому контуру.
UPDATE refresh_sessions
SET revoked_at = now()
WHERE revoked_at IS NULL;

-- Комментарии к броням пишут люди, и там встречаются телефоны и адреса
UPDATE bookings
SET note = NULL,
    cancel_reason = NULL;

-- Идентификаторы удержаний ведут в платёжный шлюз: в тестовом контуре
-- они бесполезны и опасны одновременно
UPDATE bookings
SET payment_hold_id = NULL;

-- Журнал действий хранит произвольную полезную нагрузку
UPDATE audit_records
SET payload = '{}'::jsonb;

-- Ключи идемпотентности содержат сохранённые тела ответов
TRUNCATE idempotency_records;

COMMIT;

-- После обезличивания стоит обновить статистику: планировщик запросов
-- строил её по прежнему распределению значений.
ANALYZE;
